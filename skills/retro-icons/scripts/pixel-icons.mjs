#!/usr/bin/env node
// Pixel icons from ASCII grids. One JSON source in, crisp SVGs out.
//
// Usage: node pixel-icons.mjs <icons.json> <out-dir> [--sprite] [--react] [--only name,name]
//
// icons.json: { "palette": { "k": "#000000", ... }, "icons": { "folder": ["....kkkk....", ...], ... } }
//   Each icon is a square grid (16x16 by default; 32x32 also works). "." is transparent.
//   Every other character must be a palette key.
//
// Writes:
//   <out-dir>/<name>.svg        one file per icon, shape-rendering="crispEdges"
//   <out-dir>/preview.html      every icon at 1x, 2x, 3x on grey and white, to eyeball them
//   <out-dir>/sprite.svg        with --sprite: <symbol id="icon-<name>"> for <svg><use href="sprite.svg#icon-folder"/></svg>
//   <out-dir>/PixelIcons.jsx    with --react: one component per icon, <FolderIcon size={16} />
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const [src, out, ...flags] = process.argv.slice(2);
if (!src || !out) { console.error("Usage: node pixel-icons.mjs <icons.json> <out-dir> [--sprite] [--react] [--only a,b]"); process.exit(2); }
const { palette, icons } = JSON.parse(readFileSync(src, "utf8"));
const onlyIdx = flags.indexOf("--only");
const only = onlyIdx >= 0 ? new Set(flags[onlyIdx + 1].split(",")) : null;
mkdirSync(out, { recursive: true });

// merge horizontal runs into rects, then merge identical runs straight below them into taller rects
const toRects = (name, rows) => {
  const n = rows.length;
  rows.forEach((r, y) => {
    if (r.length !== n) throw new Error(`${name}: row ${y} is ${r.length} wide, expected ${n} ("${r}")`);
  });
  const runs = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < n;) {
      const c = row[x]; let w = 1;
      while (x + w < n && row[x + w] === c) w++;
      if (c !== ".") {
        if (!palette[c]) throw new Error(`${name}: "${c}" at ${x},${y} is not in the palette`);
        runs.push({ x, y, w, h: 1, c });
      }
      x += w;
    }
  });
  const merged = [];
  for (const r of runs) {
    const above = merged.find((m) => m.x === r.x && m.w === r.w && m.c === r.c && m.y + m.h === r.y);
    if (above) above.h++; else merged.push({ ...r });
  }
  return { n, body: merged.map((r) => `<rect x="${r.x}" y="${r.y}" width="${r.w}" height="${r.h}" fill="${palette[r.c]}"/>`).join("") };
};

const names = Object.keys(icons).filter((k) => !only || only.has(k));
const built = names.map((name) => ({ name, ...toRects(name, icons[name]) }));

for (const { name, n, body } of built) {
  writeFileSync(`${out}/${name}.svg`, `<svg xmlns="http://www.w3.org/2000/svg" width="${n}" height="${n}" viewBox="0 0 ${n} ${n}" shape-rendering="crispEdges">${body}</svg>\n`);
}

if (flags.includes("--sprite")) {
  writeFileSync(`${out}/sprite.svg`, `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n` +
    built.map(({ name, n, body }) => `<symbol id="icon-${name}" viewBox="0 0 ${n} ${n}" shape-rendering="crispEdges">${body}</symbol>`).join("\n") + `\n</svg>\n`);
}

if (flags.includes("--react")) {
  const pascal = (s) => s.replace(/(^|[-_ ])(\w)/g, (_, __, c) => c.toUpperCase());
  writeFileSync(`${out}/PixelIcons.jsx`,
    `// Generated by pixel-icons.mjs. Sizes: 16, 32 or 48 only, so pixels stay square.\n` +
    `const Pixel = ({ n, size = n, label, children, ...rest }) => (\n` +
    `  <svg width={size} height={size} viewBox={\`0 0 \${n} \${n}\`} shapeRendering="crispEdges" style={{ imageRendering: "pixelated", flex: "none" }}\n` +
    `    role={label ? "img" : undefined} aria-label={label} aria-hidden={label ? undefined : true} {...rest}>{children}</svg>\n);\n\n` +
    built.map(({ name, n, body }) => `export const ${pascal(name)}Icon = (p) => <Pixel n={${n}} {...p}>${body.replace(/<rect ([^>]*)\/>/g, "<rect $1 />")}</Pixel>;`).join("\n") + "\n");
}

const cell = (name, bg) => `<figure style="margin:0;text-align:center;font:12px system-ui;color:#333">
  <div style="background:${bg};padding:8px;display:flex;gap:8px;align-items:end;justify-content:center">
    ${[1, 2, 3].map((s) => `<img src="${name}.svg" width="${16 * s}" height="${16 * s}" style="image-rendering:pixelated">`).join("")}
  </div><figcaption>${name}</figcaption></figure>`;
writeFileSync(`${out}/preview.html`, `<!doctype html><meta charset="utf-8"><title>Pixel icons</title>
<body style="margin:0;padding:16px;background:#fff;display:grid;grid-template-columns:repeat(auto-fill,minmax(150px,1fr));gap:12px">
${built.map((b, i) => cell(b.name, i % 2 ? "#ffffff" : "#c0c0c0")).join("\n")}
</body>\n`);

console.log(`${built.length} icon(s) -> ${out}`);
